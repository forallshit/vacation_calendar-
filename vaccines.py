def get_vaccines_for_child(birth_date, today):
    """
    Возвращает список прививок с рассчитанной датой для конкретного ребёнка.
    birth_date, today — объекты datetime.date
    """
    results = []
    for v in VACCINE_SCHEDULE:
        from datetime import timedelta
        due_date = birth_date + timedelta(days=v["days"])
        results.append({
            "id": v["id"],
            "name": v["name"],
            "info": v["info"],
            "due_date": due_date,
            "days_left": (due_date - today).days,
        })
    return results


def get_vaccine_name_by_id(vaccine_id: str):
    for v in VACCINE_SCHEDULE:
        if v["id"] == vaccine_id:
            return v["name"]
    return vaccine_id


def get_vaccine_by_id(vaccine_id: str):
    """Возвращает словарь с полными данными о прививке (name, info) или None."""
    for v in VACCINE_SCHEDULE:
        if v["id"] == vaccine_id:
            return v
    return None
